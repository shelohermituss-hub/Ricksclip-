"""Install the skill and its helper agents for Claude Code, then check the PC.
    python tools/install.py          install + check
    python tools/install.py --check  only check what is installed
Run it once after you unzip, and again if you move the folder. After that, tools/refresh_installed_skill.py keeps the
installed copy up to date (STEP 0 of every film runs it).

This folder stays the working copy (rules, tools, templates, episodes). The installer writes a copy of SKILL.md to
~/.claude/skills/cartoon-3d-short/ with every path made absolute, copies agents/*.md to ~/.claude/agents/ the same way,
and makes the rule slices in rules/dept/. Nothing else on the PC is changed."""
import os, re, glob, sys, shutil, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))).replace("\\", "/")
HOME = os.path.expanduser("~")
FRONT = re.compile(r"\A---\n(.*?)\n---\n", re.S)
DIRS = r"(templates|tools|references|library|episodes|agents|rules|cloud_rules)"
# CLOUD (Claude Code on the web): the repo is cloned fresh in every session and the home folder is thrown away, so the skill and
# the helpers are installed INSIDE the repo (.claude/skills, .claude/agents) and committed. Paths stay relative to the repo root,
# which is the session's working folder. On a PC use plain `python tools/install.py`; force either way with --project / --home.
CLOUD = ("--project" in sys.argv or bool(os.environ.get("CLAUDE_CODE_REMOTE"))) and "--home" not in sys.argv
BASE = os.path.join(ROOT, ".claude") if CLOUD else os.path.join(HOME, ".claude")


def ABS(s):
    if CLOUD:
        return s
    return re.sub(r"(?<![\w/\\.:-])" + DIRS + r"/", ROOT + r"/\1/", s)


def install():
    subprocess.run([sys.executable, os.path.join(ROOT, "tools", "slice_rules.py")], check=True, stdout=subprocess.DEVNULL)
    print("rule slices ->", os.path.join(ROOT, "rules", "dept"))
    master = open(os.path.join(ROOT, "SKILL.md"), encoding="utf-8").read()
    m = FRONT.match(master)
    body = ABS(master[m.end():])
    body = re.sub(r"\]\((WORKFLOW|DENSITY_RULES|HANDOFF|FILE_GUIDE|CINEMATOGRAPHY|CB_RULES|START_HERE|INSTALL|SOUND_AND_MUSIC|TOKEN_SAVING)\.md\)",
                  lambda k: "](%s/%s.md)" % ("../../.." if CLOUD else ROOT.replace(" ", "%20"), k.group(1)), body)
    note = "\n> **This is an installed copy.** The master copy is `%s/SKILL.md`. Do not edit this file: after any change to the master, run `python \"%s/tools/refresh_installed_skill.py\"`.\n" % (ROOT, ROOT)
    if CLOUD:
        note = "\n> **This is an installed copy (cloud).** The master copy is `SKILL.md` in the repo root. Every path in this skill is relative to the repo root, which is the session's working folder. Do not edit this file: after any change to the master, run `python tools/refresh_installed_skill.py` and commit. Read `CLAUDE.md` for what is different in the cloud.\n"
    dst = os.path.join(BASE, "skills", "cartoon-3d-short")
    os.makedirs(dst, exist_ok=True)
    open(os.path.join(dst, "SKILL.md"), "w", encoding="utf-8", newline="\n").write(m.group(0) + note + body)
    print("installed skill ->", os.path.join(dst, "SKILL.md"))
    adst = os.path.join(BASE, "agents")
    os.makedirs(adst, exist_ok=True)
    for p in sorted(glob.glob(os.path.join(ROOT, "agents", "*.md"))):
        a = open(p, encoding="utf-8").read()
        k = FRONT.match(a)
        a = k.group(0) + (a[k.end():] if CLOUD else ABS(a[k.end():]).replace("`CINEMATOGRAPHY.md`", "`%s/CINEMATOGRAPHY.md`" % ROOT).replace("`SKILL.md`", "`%s/SKILL.md`" % ROOT))
        open(os.path.join(adst, os.path.basename(p)), "w", encoding="utf-8", newline="\n").write(a)
        print("installed agent ->", os.path.basename(p))


def ver(cmd):
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=30, shell=(os.name == "nt" and cmd[0] in ("npm", "npx")))
        return (r.stdout or r.stderr).strip().splitlines()[0] if r.returncode == 0 else None
    except Exception:
        return None


def check():
    ok = True
    print("\nChecking this " + ("cloud session" if CLOUD else "PC"))

    def line(name, found, need, fix):
        nonlocal ok
        print("  %-4s %-26s %s" % ("ok" if found else need, name, found or fix))
        if not found and need == "MISS":
            ok = False

    line("Python 3.10+", sys.version.split()[0] if sys.version_info >= (3, 10) else None, "MISS", "install Python 3.10 or newer from python.org")
    for mod, pipname, need, why in (("numpy", "numpy", "MISS", ""), ("PIL", "pillow", "MISS", ""), ("scipy", "scipy", "MISS", " (checks and the sound mix)"),
                                    ("soundfile", "soundfile", "MISS", " (the sound mix)"), ("cv2", "opencv-python", "opt", " (look measurements)"),
                                    ("faster_whisper", "faster-whisper", "opt", " (word timing of the voice)")):
        try:
            __import__(mod); found = "installed"
        except Exception:
            found = None
        line("python: " + pipname, found, need, "pip install " + pipname + why)
    node = ver(["node", "--version"])
    line("Node 18+", node if node and int(node.lstrip("v").split(".")[0]) >= 18 else None, "MISS", "install Node LTS from nodejs.org")
    line("ffmpeg", (ver(["ffmpeg", "-version"]) or "")[:40] or None, "MISS", "install ffmpeg and put it on the PATH (Windows: winget install Gyan.FFmpeg)")
    pw = any(os.path.isdir(os.path.join(ROOT, d, "node_modules", "playwright")) for d in ("", "templates/threejs_film"))
    pk = os.path.exists(os.path.join(ROOT, "templates", "vector2d_characters", "code", "char2d.mjs"))
    line("character package", "found" if pk else None, "MISS", "templates/vector2d_characters/code/char2d.mjs is missing: unzip the skill again, no character can be drawn without it")
    line("playwright (film kit)", "installed" if pw else None, "MISS", 'in "%s" run: npm install   then: npx playwright install chromium' % ROOT)
    sc = os.path.join(ROOT, "templates", "sound_kit", "sound_config.json")
    line("sound library config", "set" if os.path.exists(sc) else None, "opt", "copy templates/sound_kit/sound_config.example.json to sound_config.json and add your folders (SOUND_AND_MUSIC.md)")
    print("\nAll needed parts are there." if ok else "\nInstall the parts marked MISS, then run this again.")
    print("Next: open Claude Code in this folder and paste START_FILM_PROMPT.md (or follow INSTALL.md step 6).")
    return ok


if __name__ == "__main__":
    if "--check" not in sys.argv:
        install()
    sys.exit(0 if check() else 1)
